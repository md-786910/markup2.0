const axios = require('axios');
const Project = require('../models/Project');
const fileStorage = require('./fileStorage');
const { logger } = require('./logger');

// Website project thumbnails. A new website project first points at the
// WordPress mshots screenshot URL (shown at once); in the background the server
// waits for mshots to finish the capture, stores the JPEG with the active file
// storage provider (local disk or Cloudinary, uploads/thumbnails/) and switches
// Project.thumbnail to that stored path. The app shows relative paths through
// the API (fileUrl), so nothing changes on the client.
//
// mshots answers 307 (to /mshots/v1/default) while it captures, then 200 with
// image/jpeg. Thumbnails are generated by us, so they don't count against the
// organization's storage quota.

const MSHOTS_PREFIX = 'https://s0.wp.com/mshots/v1/';
const MAX_BYTES = 5 * 1024 * 1024;
// Waits between attempts: about 2.5 minutes in all
const RETRY_DELAYS_MS = [0, 5000, 10000, 15000, 20000, 30000, 30000, 45000];
const STORED_PREFIX = 'uploads/thumbnails/';

const inFlight = new Set();
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

function normalizeWebsiteUrl(websiteUrl) {
  return /^https?:\/\//i.test(websiteUrl) ? websiteUrl : `https://${websiteUrl}`;
}

/** The mshots URL used as the immediate thumbnail of a website. */
function mshotsUrl(websiteUrl) {
  return `${MSHOTS_PREFIX}${encodeURIComponent(normalizeWebsiteUrl(websiteUrl))}?w=900`;
}

const isMshotsUrl = (value) => typeof value === 'string' && value.startsWith(MSHOTS_PREFIX);
const isStoredThumbnail = (value) => typeof value === 'string' && value.startsWith(STORED_PREFIX);

// One attempt: the JPEG when the capture is ready, else null
async function fetchCapture(url) {
  const res = await axios.get(url, {
    headers: { 'User-Agent': 'Mozilla/5.0 (compatible; Kommently thumbnails)' },
    maxRedirects: 0, // a redirect means "still capturing"
    responseType: 'arraybuffer',
    maxContentLength: MAX_BYTES,
    timeout: 20000,
    validateStatus: () => true,
  });
  const type = String(res.headers['content-type'] || '');
  if (res.status === 200 && type.startsWith('image/jpeg') && res.data?.length) return Buffer.from(res.data);
  return null;
}

/**
 * Store the screenshot of a website project whose thumbnail is still the
 * mshots URL. Fire-and-forget; safe to call more than once (one capture per
 * project per process; the save only applies while the thumbnail is unchanged).
 */
async function storeWebsiteThumbnail(projectId) {
  const key = String(projectId);
  if (inFlight.has(key)) return;
  inFlight.add(key);
  try {
    const project = await Project.findById(projectId).select('thumbnail organization projectType');
    if (!project || project.projectType !== 'website' || !isMshotsUrl(project.thumbnail)) return;
    const source = project.thumbnail;

    let image = null;
    for (const delay of RETRY_DELAYS_MS) {
      if (delay) await sleep(delay);
      try {
        image = await fetchCapture(source);
      } catch (err) {
        logger.debug({ err: err.message, projectId: key }, 'Thumbnail capture attempt failed');
      }
      if (image) break;
    }
    if (!image) {
      logger.info({ projectId: key }, 'Website thumbnail not ready: keeping the mshots link');
      return;
    }

    const stored = await fileStorage.saveBuffer(image, { subdir: 'thumbnails', ext: '.jpg', mimetype: 'image/jpeg' });
    // Only while nothing else changed it (URL edited, project deleted meanwhile)
    const result = await Project.updateOne({ _id: project._id, thumbnail: source }, { $set: { thumbnail: stored } });
    if (!result.modifiedCount) {
      fileStorage.deleteStoredFiles([stored]);
      return;
    }
    require('./liveSync').publish(project.organization, ['projects', 'project'], key);
  } catch (err) {
    logger.warn({ err: err.message, projectId: key }, 'Storing the website thumbnail failed');
  } finally {
    inFlight.delete(key);
  }
}

/**
 * Store thumbnails of existing website projects that still point at mshots.
 * Runs once at server start (one worker in cluster mode), one project at a time.
 */
async function backfillWebsiteThumbnails() {
  const projects = await Project.find({ projectType: 'website', thumbnail: { $regex: '^https://s0\\.wp\\.com/mshots/v1/' } })
    .select('_id')
    .lean();
  for (const p of projects) await storeWebsiteThumbnail(p._id);
  if (projects.length) logger.info({ count: projects.length }, 'Website thumbnail backfill done');
}

module.exports = { mshotsUrl, isMshotsUrl, isStoredThumbnail, storeWebsiteThumbnail, backfillWebsiteThumbnails };
