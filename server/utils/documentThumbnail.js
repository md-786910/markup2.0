const fs = require('fs');
const Project = require('../models/Project');
const fileStorage = require('./fileStorage');
const { logger } = require('./logger');

// Document project thumbnails for the dashboard cards. Without one, a card
// downloaded the whole first file: every PDF in full (pdf.js rendered page 1
// in the browser) and images at full resolution. Here the server renders the
// first page (PDF) or scales the first image down once, stores a small WebP in
// uploads/thumbnails/ and points Project.thumbnail at it. The original files
// are untouched; the project page still opens them in full.
//
// Generated by us, so not counted in the storage quota; deleted by the project
// cascade (utils/cascade.js removes thumbnails under uploads/thumbnails/).

const WIDTH = 600; // cards are ~300 CSS px wide: sharp on 2x screens
const QUALITY = 80;
const MAX_SOURCE_BYTES = 60 * 1024 * 1024;
const RASTER_TYPES = new Set(['image/png', 'image/jpeg', 'image/webp', 'image/gif']);
const STORED_PREFIX = 'uploads/thumbnails/';

const inFlight = new Set();

const isPdf = (doc) => doc?.mimetype === 'application/pdf';
const isRaster = (doc) => RASTER_TYPES.has(doc?.mimetype);

/** Can a thumbnail be made for this document file? */
function canThumbnail(doc) {
  return isPdf(doc) || isRaster(doc);
}

async function toWebp(source) {
  const { createCanvas, loadImage } = require('@napi-rs/canvas');
  const img = await loadImage(source);
  if (!img.width || !img.height) return null;
  const scale = Math.min(1, WIDTH / img.width);
  const w = Math.max(1, Math.round(img.width * scale));
  const h = Math.max(1, Math.round(img.height * scale));
  const canvas = createCanvas(w, h);
  const ctx = canvas.getContext('2d');
  ctx.fillStyle = '#ffffff'; // transparent PNGs/PDF pages on white, as shown
  ctx.fillRect(0, 0, w, h);
  ctx.drawImage(img, 0, 0, w, h);
  return canvas.encode('webp', QUALITY);
}

/** WebP thumbnail of a document file's first page/frame, or null. */
async function renderDocumentThumbnail(buffer, mimetype) {
  if (!buffer?.length || buffer.length > MAX_SOURCE_BYTES) return null;
  if (RASTER_TYPES.has(mimetype)) return toWebp(buffer);
  if (mimetype !== 'application/pdf') return null;
  const { PDFParse } = require('pdf-parse');
  // pdf.js may detach the buffer it is given: pass a copy
  const parser = new PDFParse({ data: new Uint8Array(buffer) });
  try {
    const shot = await parser.getScreenshot({ partial: [1], desiredWidth: WIDTH, imageBuffer: true, imageDataUrl: false });
    const page = shot?.pages?.[0];
    return page?.data?.length ? toWebp(Buffer.from(page.data)) : null;
  } finally {
    await parser.destroy().catch(() => {});
  }
}

// The stored bytes of an upload: the local file, else (Cloudinary) a download
async function readStoredFile(relPath) {
  const parsed = fileStorage.parseStoredPath(relPath);
  if (!parsed) return null;
  const local = fileStorage.localFile(parsed);
  if (local) {
    try { return await fs.promises.readFile(local); } catch { /* not on this disk */ }
  }
  const url = fileStorage.remoteUrl(parsed);
  if (!url) return null;
  const axios = require('axios');
  const res = await axios.get(url, { responseType: 'arraybuffer', maxContentLength: MAX_SOURCE_BYTES, timeout: 30000 });
  return Buffer.from(res.data);
}

/**
 * Make and store the thumbnail of a document project. Fire-and-forget; safe to
 * call more than once. `source` ({ buffer, mimetype }) is the first file's
 * bytes when the caller has them (project creation), else they are read from
 * storage. Applies only while Project.thumbnail is unchanged.
 */
async function storeDocumentThumbnail(projectId, source = null) {
  const key = String(projectId);
  if (inFlight.has(key)) return;
  inFlight.add(key);
  try {
    const project = await Project.findById(projectId).select('thumbnail organization projectType documents').lean();
    if (!project || project.projectType !== 'document') return;
    if (typeof project.thumbnail === 'string' && project.thumbnail.startsWith(STORED_PREFIX)) return;
    const first = [...(project.documents || [])].sort((a, b) => (a.order || 0) - (b.order || 0))[0];
    if (!canThumbnail(first)) return;

    const buffer = source?.buffer || await readStoredFile(first.path);
    const image = await renderDocumentThumbnail(buffer, source?.mimetype || first.mimetype);
    if (!image) return;

    const stored = await fileStorage.saveBuffer(image, { subdir: 'thumbnails', ext: '.webp', mimetype: 'image/webp' });
    const result = await Project.updateOne({ _id: project._id, thumbnail: project.thumbnail }, { $set: { thumbnail: stored } });
    if (!result.modifiedCount) {
      fileStorage.deleteStoredFiles([stored]);
      return;
    }
    require('./liveSync').publish(project.organization, ['projects', 'project'], key);
  } catch (err) {
    logger.warn({ err: err.message, projectId: key }, 'Document thumbnail failed');
  } finally {
    inFlight.delete(key);
  }
}

/**
 * Thumbnails for existing document projects (PDFs had none; images pointed at
 * the full-size original). Runs once at server start, one project at a time.
 */
async function backfillDocumentThumbnails() {
  const projects = await Project.find({
    projectType: 'document',
    thumbnail: { $not: /^uploads\/thumbnails\// }, // also matches null / missing
    'documents.mimetype': { $in: ['application/pdf', ...RASTER_TYPES] },
  }).select('_id').lean();
  for (const p of projects) await storeDocumentThumbnail(p._id);
  if (projects.length) logger.info({ count: projects.length }, 'Document thumbnail backfill done');
}

module.exports = { renderDocumentThumbnail, storeDocumentThumbnail, backfillDocumentThumbnails, canThumbnail };
