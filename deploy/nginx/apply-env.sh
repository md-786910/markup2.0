#!/bin/sh
# Writes the values nginx needs from the repo's .env into
# /etc/nginx/conf.d/kommently-env.conf and reloads nginx. Run after changing
# API_PORT, API_URL or POSTHOG_HOST, after moving the repo, and after copying a
# new kommently.conf:  sudo sh deploy/nginx/apply-env.sh
set -e
REPO=$(cd "$(dirname "$0")/../.." && pwd)

# One value from .env (last one wins), without quotes, spaces or CR
env_value() {
  grep -E "^$1=" "$REPO/.env" 2>/dev/null | tail -n1 | cut -d= -f2- | tr -d ' "\r'"'"
}

# An origin (scheme://host[:port], no path); anything else falls back to $2
origin_or() {
  o=$(printf '%s' "$1" | sed -E 's#^(https?://[A-Za-z0-9.-]+(:[0-9]+)?)/*$#\1#')
  case "$o" in
    http://*|https://*)
      if printf '%s' "$o" | grep -Eq '^https?://[A-Za-z0-9.-]+(:[0-9]+)?$'; then echo "$o"; return; fi ;;
  esac
  echo "$2"
}

API_PORT=$(env_value API_PORT)
API_PORT=${API_PORT:-5000}
case "$API_PORT" in ''|*[!0-9]*) echo "API_PORT in .env is not a number" >&2; exit 1 ;; esac

# Used in the Content-Security-Policy of the app, admin and website hosts
API_ORIGIN=$(origin_or "$(env_value API_URL)" "https://api.kommently.info")
case "$API_ORIGIN" in
  https://*) API_WS="wss://${API_ORIGIN#https://}" ;;
  *)         API_WS="ws://${API_ORIGIN#http://}" ;;
esac
POSTHOG_ORIGIN=$(origin_or "$(env_value POSTHOG_HOST)" "https://eu.i.posthog.com")

cat > /etc/nginx/conf.d/kommently-env.conf <<CONF
# Generated by deploy/nginx/apply-env.sh from $REPO/.env; do not edit.
upstream kommently_api { server 127.0.0.1:$API_PORT; keepalive 16; }
map "" \$kommently_repo { default $REPO; }
map "" \$kommently_api_origin { default "$API_ORIGIN"; }
map "" \$kommently_api_ws { default "$API_WS"; }
map "" \$kommently_posthog_origin { default "$POSTHOG_ORIGIN"; }
CONF
nginx -t && systemctl reload nginx
echo "nginx: API on 127.0.0.1:$API_PORT ($API_ORIGIN), frontends from $REPO/{client,admin,website}/build"
